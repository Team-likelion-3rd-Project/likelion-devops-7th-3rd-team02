-- V8: 업무 첨부파일 (Backend-API-구현-목록 15장)
-- 파일 본문은 저장소(S3 또는 로컬 디렉터리)에, 이 테이블에는 메타데이터만 둔다.
CREATE TABLE task_attachments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       BIGINT        NOT NULL,
    project_id    BIGINT        NOT NULL,
    uploader_id   BIGINT        NOT NULL,
    original_name VARCHAR(255)  NOT NULL,
    content_type  VARCHAR(100)  NOT NULL,
    size_bytes    BIGINT        NOT NULL,
    storage_key   VARCHAR(300)  NOT NULL,
    created_at    TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_attachment_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_attachment_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_attachment_uploader FOREIGN KEY (uploader_id) REFERENCES users (id),
    CONSTRAINT uk_attachment_storage_key UNIQUE (storage_key)
);

CREATE INDEX idx_task_attachments_task ON task_attachments (task_id, id);
