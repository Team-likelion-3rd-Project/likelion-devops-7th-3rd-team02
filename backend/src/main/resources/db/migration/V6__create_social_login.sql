-- V6: 소셜 로그인 (Backend-API-구현-목록 X1~X3 / ERD 4.6)

-- 소셜 로그인만 쓰는 사용자는 비밀번호가 없다 (이메일 로그인 시 INVALID_CREDENTIALS)
ALTER TABLE users ALTER COLUMN password DROP NOT NULL;

-- 사용자 ↔ GitHub·Google 계정 연결. 제공자 접근 토큰은 저장하지 않는다.
CREATE TABLE user_identities (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    provider         VARCHAR(20)  NOT NULL,
    provider_user_id VARCHAR(100) NOT NULL,
    provider_login   VARCHAR(100),
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_user_identities_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_user_identities_provider CHECK (provider IN ('GITHUB', 'GOOGLE')),
    CONSTRAINT uk_user_identities_provider_user UNIQUE (provider, provider_user_id),
    -- 한 사용자에게 같은 제공자 계정은 하나만 (다른 계정이 오면 account_conflict)
    CONSTRAINT uk_user_identities_user_provider UNIQUE (user_id, provider)
);

-- 소셜 로그인 성공 후 Frontend에 넘기는 1회용 code (60초, 1회). 원문이 아닌 SHA-256 해시만 저장
CREATE TABLE oauth_login_codes (
    code_hash  VARCHAR(64)  PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_oauth_login_codes_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_oauth_login_codes_expires_at ON oauth_login_codes (expires_at);
