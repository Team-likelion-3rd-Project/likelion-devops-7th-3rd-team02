-- V4: 장애 (Backend-API-구현-목록 I1~I7 / ERD 4.3)
-- Alertmanager Webhook(I5)으로 만들어지고, 팀원이 확인·담당자 지정·해결한다.

CREATE TABLE incidents (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id           BIGINT           NOT NULL,
    title                VARCHAR(200)     NOT NULL,
    status               VARCHAR(20)      NOT NULL,
    severity             VARCHAR(20)      NOT NULL,
    source               VARCHAR(30)      NOT NULL,
    fingerprint          VARCHAR(255)     NOT NULL,
    assignee_id          BIGINT,
    summary              VARCHAR(300),
    metric_name          VARCHAR(100),
    metric_current_value DOUBLE PRECISION,
    metric_threshold     DOUBLE PRECISION,
    metric_unit          VARCHAR(20),
    firing               BOOLEAN          NOT NULL,
    -- 알림이 풀린 시각. 자동 해결(확인됨 + 30분 안정)의 기준
    firing_ended_at      TIMESTAMP(6),
    occurred_at          TIMESTAMP(6)     NOT NULL,
    acknowledged_at      TIMESTAMP(6),
    resolved_at          TIMESTAMP(6),
    created_at           TIMESTAMP(6)     NOT NULL,
    updated_at           TIMESTAMP(6)     NOT NULL,
    CONSTRAINT fk_incidents_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_incidents_assignee FOREIGN KEY (assignee_id) REFERENCES users (id),
    CONSTRAINT ck_incidents_status CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
    CONSTRAINT ck_incidents_severity CHECK (severity IN ('CRITICAL', 'WARNING', 'INFO'))
);

-- 장애 목록(I1)·전체 장애(I7)·대시보드 배너
CREATE INDEX idx_incidents_project_status_occurred ON incidents (project_id, status, occurred_at DESC);

-- 같은 알림은 해결 전까지 장애 하나만. 해결 뒤 다시 울리면 새 장애를 만든다 (I6 규칙)
CREATE UNIQUE INDEX uk_incidents_active_fingerprint
    ON incidents (project_id, fingerprint)
    WHERE status <> 'RESOLVED';

-- 자동 해결 대상 찾기
CREATE INDEX idx_incidents_auto_resolve ON incidents (status, firing, firing_ended_at);
