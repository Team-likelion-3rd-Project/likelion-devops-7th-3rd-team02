-- V3: 배포 기록 (Backend-API-구현-목록 D1, D3 / ERD 4.5)
-- CI·GitOps 배포 검증 단계가 D3 Webhook으로 보낸 결과를 저장한다.
-- (ERD 계획의 V3 연동 테이블은 GitHub 저장소 연동 범위 제외로 만들지 않아 번호를 당겼다)

CREATE TABLE deployments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     BIGINT        NOT NULL,
    environment    VARCHAR(30)   NOT NULL,
    service        VARCHAR(30)   NOT NULL,
    commit_sha     VARCHAR(40)   NOT NULL,
    commit_message VARCHAR(300),
    image_tag      VARCHAR(100)  NOT NULL,
    image_digest   VARCHAR(100),
    revision       INTEGER,
    status         VARCHAR(20)   NOT NULL,
    pipeline_id    BIGINT,
    deployed_at    TIMESTAMP(6)  NOT NULL,
    created_at     TIMESTAMP(6)  NOT NULL,
    updated_at     TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_deployments_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_deployments_status CHECK (status IN ('IN_PROGRESS', 'SUCCESS', 'FAILED')),
    -- 같은 파이프라인의 시작(IN_PROGRESS)·완료 기록은 한 행을 갱신한다
    CONSTRAINT uk_deployments_project_pipeline_service UNIQUE (project_id, pipeline_id, service)
);

-- 배포 이력·최근 배포 (deployed_at 최신순)
CREATE INDEX idx_deployments_project_deployed_at ON deployments (project_id, deployed_at DESC);
