ALTER TABLE incidents ADD COLUMN environment VARCHAR(30);

CREATE INDEX idx_incidents_project_environment_status ON incidents (project_id, environment, status);

CREATE TABLE project_integrations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT       NOT NULL,
    provider      VARCHAR(20)  NOT NULL,
    external_path VARCHAR(200) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_project_integrations_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_project_integrations_provider CHECK (provider IN ('GITHUB')),
    CONSTRAINT uk_project_integrations_project_provider UNIQUE (project_id, provider)
);
