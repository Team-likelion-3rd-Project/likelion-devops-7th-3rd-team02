-- V7: 프로젝트별 클라우드 연결 (Backend-API-구현-목록 14장)
-- 운영 상태 API가 서버 설정 대신 프로젝트에 등록된 환경을 조회한다.

CREATE TABLE project_cloud_environments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id            BIGINT        NOT NULL,
    name                  VARCHAR(30)   NOT NULL,
    label                 VARCHAR(50)   NOT NULL,
    is_default            BOOLEAN       NOT NULL,
    prometheus_url        VARCHAR(300),
    -- Bearer 토큰은 AES-GCM 암호문(base64)만 저장
    prometheus_token_enc  VARCHAR(1000),
    k8s_namespace         VARCHAR(63)   NOT NULL,
    app_deployment        VARCHAR(63),
    metrics_job           VARCHAR(100),
    node_label            VARCHAR(30)   NOT NULL,
    aws_region            VARCHAR(30),
    aws_role_arn          VARCHAR(200),
    -- DevFlow가 환경마다 만드는 값. 사용자 역할 신뢰 정책의 sts:ExternalId 조건에 넣는다
    aws_external_id       VARCHAR(64)   NOT NULL,
    aws_rds_instance_id   VARCHAR(100),
    aws_load_balancer_arn VARCHAR(300),
    aws_target_group_arn  VARCHAR(300),
    created_at            TIMESTAMP(6)  NOT NULL,
    updated_at            TIMESTAMP(6)  NOT NULL,
    CONSTRAINT fk_cloud_env_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT uk_cloud_env_project_name UNIQUE (project_id, name)
);

-- 프로젝트별 Webhook 토큰 (배포 기록 D3, Alertmanager I5). 원문은 발급 때 한 번만, 저장은 SHA-256
CREATE TABLE project_webhook_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT       NOT NULL,
    type         VARCHAR(20)  NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL,
    created_at   TIMESTAMP(6) NOT NULL,
    last_used_at TIMESTAMP(6),
    CONSTRAINT fk_webhook_token_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_webhook_token_type CHECK (type IN ('DEPLOYMENT', 'ALERTMANAGER')),
    CONSTRAINT uk_webhook_token_project_type UNIQUE (project_id, type),
    CONSTRAINT uk_webhook_token_hash UNIQUE (token_hash)
);
